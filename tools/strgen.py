#!/usr/bin/env python3
"""Generate (doom dstrings) from linuxdoom's d_englsh.h: strgen.py SRCDIR OUT.

Each `#define NAME value` becomes a definition. A value is a sequence of C
string literals and earlier names, concatenated; a character literal ('g')
becomes its character code.
"""
import re
import sys

src = open(sys.argv[1] + "/d_englsh.h").read()
src = re.sub(r"/\*.*?\*/", " ", src, flags=re.S)
src = src.replace("\\\n", " ")
TOKEN = re.compile(r'\s*(?:("(?:[^"\\]|\\.)*")|(\'(?:[^\'\\]|\\.)\')|([A-Za-z_]\w*))')

defs, values = [], {}
for line in src.split("\n"):
    m = re.match(r"\s*#define\s+(\w+)\s*(.*)$", line)
    if not m or not m.group(2).strip():
        continue
    name, rest = m.group(1), re.sub(r"//.*$", "", m.group(2)).strip()
    parts, pos, char = [], 0, None
    while pos < len(rest):
        t = TOKEN.match(rest, pos)
        if not t:
            sys.exit("can't parse %s: %r" % (name, rest[pos:]))
        pos = t.end()
        if t.group(1):
            parts.append(t.group(1)[1:-1])
        elif t.group(2):
            char = ord(t.group(2)[1:-1].encode().decode("unicode_escape"))
        else:
            parts.append(values[t.group(3)])
        rest_tail = rest[pos:].strip()
        if not rest_tail:
            break
    if char is not None:
        values[name] = None
        defs.append("  (define %s %d)" % (name, char))
    else:
        s = "".join(parts)
        values[name] = s
        defs.append('  (define %s "%s")' % (name, s))

names = [d.split()[1] for d in defs]
with open(sys.argv[2], "w") as out:
    out.write(";;; GENERATED by tools/strgen.py from linuxdoom-1.10's d_englsh.h. Do not edit.\n")
    out.write(";;; dstrings: user-visible strings (dstrings.h / d_englsh.h). String\n")
    out.write(";;; escapes are C's, which Scheme reads the same way.\n")
    out.write("(library (doom dstrings)\n  (export\n   %s)\n  (import (chezscheme))\n\n%s)\n"
              % ("\n   ".join(names), "\n".join(defs)))
print("dstrings: %d strings" % len(defs))
