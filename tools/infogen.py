#!/usr/bin/env python3
"""Generate (doom info) and (doom sounds) from linuxdoom's info.[ch] and sounds.[ch].

    infogen.py SRCDIR OUTDIR

info.sls: the spritenum_t / statenum_t / mobjtype_t enums as constants,
sprnames, states (state records; the action is the C function's name as a
symbol, or #f, resolved to a procedure by the playsim), and mobjinfo-table
(mobjinfo records). sounds.sls: the sfxenum_t / musicenum_t enums, S_sfx and
S_music. Symbolic initializers (S_*, sfx_*, MF_* flags, FRACUNIT) are
evaluated here, so the generated tables hold plain integers.
"""
import os
import re
import sys

HEADER = ("#!chezscheme\n;;; GENERATED by tools/infogen.py from the linuxdoom-1.10 "
          "source. Do not edit.\n")


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", " ", src, flags=re.S)
    return re.sub(r"//[^\n]*", " ", src)


def enum(src, typename):
    """Names of `typedef enum { ... } typename;`, in order (no explicit values)."""
    m = re.search(r"typedef\s+enum\s*\{([^}]*)\}\s*%s\s*;" % typename, src)
    if not m:
        sys.exit("enum %s not found" % typename)
    names = [n.strip() for n in m.group(1).split(",") if n.strip()]
    for n in names:
        if "=" in n:
            sys.exit("explicit enum value in %s: %s" % (typename, n))
    return names


def initializer(src, decl):
    """Body of `decl ... = { ... };`."""
    m = re.search(re.escape(decl) + r"[^=]*=\s*\{", src)
    if not m:
        sys.exit("initializer %s not found" % decl)
    depth, i = 1, m.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    return src[m.end():i - 1]


def braces(body):
    """Top-level {...} groups of an initializer body."""
    out, depth, start = [], 0, None
    for i, c in enumerate(body):
        if c == "{":
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                out.append(body[start:i])
    return out


def split_top(s):
    """Split on commas not inside braces."""
    out, depth, cur = [], 0, ""
    for c in s:
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


class Evaluator:
    def __init__(self, consts):
        self.consts = consts

    def __call__(self, expr):
        def sub(m):
            name = m.group(0)
            if name not in self.consts:
                sys.exit("unknown identifier %s in %r" % (name, expr))
            return str(self.consts[name])
        py = re.sub(r"\b[A-Za-z_]\w*\b", sub, expr)
        # Only integer C arithmetic appears in these tables.
        if not re.fullmatch(r"[\d\s+\-*|()xXa-fA-F]*", py):
            sys.exit("unsupported expression %r" % expr)
        return int(eval(py))


def scm_list(name, items, per_line):
    lines = [" ".join(items[j:j + per_line]) for j in range(0, len(items), per_line)]
    return "  (define %s\n    (vector\n     %s))" % (name, "\n     ".join(lines))


def constants(names):
    return "\n".join("  (define %s %d)" % (n, i) for i, n in enumerate(names))


def main():
    srcdir, outdir = sys.argv[1], sys.argv[2]
    rd = lambda f: strip_comments(open(os.path.join(srcdir, f)).read())
    info_h, info_c = rd("info.h"), rd("info.c")
    sounds_h, sounds_c = rd("sounds.h"), rd("sounds.c")
    mobj_h = rd("p_mobj.h")

    sprites = enum(info_h, "spritenum_t")
    statenames = enum(info_h, "statenum_t")
    mobjtypes = enum(info_h, "mobjtype_t")
    sfx = enum(sounds_h, "sfxenum_t")
    music = enum(sounds_h, "musicenum_t")

    consts = {"FRACUNIT": 65536, "NULL": 0}
    for names in (sprites, statenames, mobjtypes, sfx, music):
        consts.update((n, i) for i, n in enumerate(names))
    for name, val in re.findall(r"\b(MF_\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)", mobj_h):
        consts[name] = int(val, 0)
    ev = Evaluator(consts)

    # sprnames
    sprnames = re.findall(r'"(\w+)"', initializer(info_c, "char *sprnames"))
    assert len(sprnames) == consts["NUMSPRITES"], len(sprnames)

    # states: {sprite, frame, tics, {action}, nextstate, misc1, misc2}
    states = []
    for i, entry in enumerate(braces(initializer(info_c, "state_t\tstates"))):
        f = split_top(entry)
        assert len(f) == 7, f
        action = f[3].strip("{} \t\n")
        action = "#f" if action == "NULL" else "'" + action
        states.append("(make-state %d %d %d %d %s %d %d %d) ; %s"
                      % (i, ev(f[0]), ev(f[1]), ev(f[2]), action, ev(f[4]), ev(f[5]), ev(f[6]),
                         statenames[i]))
    assert len(states) == consts["NUMSTATES"], len(states)

    # mobjinfo
    fields = ["doomednum", "spawnstate", "spawnhealth", "seestate", "seesound",
              "reactiontime", "attacksound", "painstate", "painchance", "painsound",
              "meleestate", "missilestate", "deathstate", "xdeathstate", "deathsound",
              "speed", "radius", "height", "mass", "damage", "activesound", "flags",
              "raisestate"]
    infos = []
    for i, entry in enumerate(braces(initializer(info_c, "mobjinfo_t mobjinfo"))):
        f = split_top(entry)
        assert len(f) == len(fields), (mobjtypes[i], f)
        infos.append("(make-mobjinfo %s) ; %s" % (" ".join(str(ev(x)) for x in f), mobjtypes[i]))
    assert len(infos) == consts["NUMMOBJTYPES"], len(infos)

    exports = (["state", "make-state", "state?"]
               + ["state-%s%s" % (f, s) for f in
                  ("index", "sprite", "frame", "tics", "action", "nextstate", "misc1", "misc2")
                  for s in ("", "-set!")]
               + ["mobjinfo", "make-mobjinfo", "mobjinfo?"]
               + ["mobjinfo-%s%s" % (f, s) for f in fields for s in ("", "-set!")]
               + ["sprnames", "states", "mobjinfo-table"] + sprites + statenames + mobjtypes)
    with open(os.path.join(outdir, "info.sls"), "w") as out:
        out.write(HEADER)
        out.write(";;; info: sprites, the state table, and the thing type table.\n")
        out.write("(library (doom info)\n  (export\n   %s)\n" % "\n   ".join(exports))
        out.write("  (import (chezscheme) (doom struct))\n\n")
        out.write("  ;; state_t, plus its index in states (C: state - states). action is\n"
                  "  ;; the action function's name (a symbol) or #f; the playsim replaces\n"
                  "  ;; the symbols with procedures when it starts (p-init).\n")
        out.write("  (define-struct state ()\n    (index 0) (sprite 0) (frame 0) (tics 0) (action #f)"
                  " (nextstate 0) (misc1 0) (misc2 0))\n\n")
        out.write("  ;; mobjinfo_t\n  (define-struct mobjinfo ()\n    %s)\n\n"
                  % "\n    ".join("(%s 0)" % f for f in fields))
        out.write(";; spritenum_t\n%s\n\n;; statenum_t\n%s\n\n;; mobjtype_t\n%s\n\n"
                  % (constants(sprites), constants(statenames), constants(mobjtypes)))
        out.write(scm_list("sprnames", ['"%s"' % s for s in sprnames], 12) + "\n\n")
        out.write("  (define states\n    (vector\n     %s\n     ))\n\n" % "\n     ".join(states))
        out.write("  (define mobjinfo-table\n    (vector\n     %s\n     )))\n" % "\n     ".join(infos))

    # sounds: S_sfx entries {name, singularity, priority, link, pitch, volume, data}
    sfx_rows = []
    for i, entry in enumerate(braces(initializer(sounds_c, "sfxinfo_t S_sfx[]"))):
        f = split_top(entry)
        name = f[0].strip('"')
        sing = {"false": "#f", "true": "#t"}[f[1]]
        m = re.fullmatch(r"&S_sfx\[(\w+)\]", f[3])
        link = str(consts[m.group(1)]) if m else ("#f" if f[3] == "0" else sys.exit(f[3]))
        sfx_rows.append('(make-sfxinfo "%s" %s %d %s %d %d #f 0 0) ; %s'
                        % (name, sing, ev(f[2]), link, ev(f[4]), ev(f[5]), sfx[i]))
    assert len(sfx_rows) == consts["NUMSFX"], len(sfx_rows)
    music_rows = []
    for entry in braces(initializer(sounds_c, "musicinfo_t S_music[]")):
        m = re.search(r'"(\w+)"', entry)
        music_rows.append('"%s"' % m.group(1) if m else "#f")
    assert len(music_rows) == consts["NUMMUSIC"], len(music_rows)

    sfields = ["name", "singularity", "priority", "link", "pitch", "volume"]
    exports = (["sfxinfo", "make-sfxinfo", "sfxinfo?"]
               + ["sfxinfo-%s%s" % (f, s) for f in sfields + ["data", "usefulness", "lumpnum"]
                  for s in ("", "-set!")]
               + ["S_sfx", "S_music"] + sfx + music)
    with open(os.path.join(outdir, "sounds.sls"), "w") as out:
        out.write(HEADER)
        out.write(";;; sounds: sound effect and music tables.\n")
        out.write("(library (doom sounds)\n  (export\n   %s)\n" % "\n   ".join(exports))
        out.write("  (import (chezscheme) (doom struct))\n\n")
        out.write("  ;; sfxinfo_t. link is an sfx number or #f; data, usefulness and\n"
                  "  ;; lumpnum are filled in at run time.\n")
        out.write("  (define-struct sfxinfo ()\n    (name \"\") (singularity #f) (priority 0)"
                  " (link #f) (pitch 0) (volume 0)\n    (data #f) (usefulness 0) (lumpnum 0))\n\n")
        out.write(";; sfxenum_t\n%s\n\n;; musicenum_t\n%s\n\n" % (constants(sfx), constants(music)))
        out.write("  (define S_sfx\n    (vector\n     %s\n     ))\n\n" % "\n     ".join(sfx_rows))
        out.write("  ;; S_music: lump names without the D_ prefix (#f for mus_None).\n")
        out.write(scm_list("S_music", music_rows, 10) + ")\n")


main()
