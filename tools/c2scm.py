#!/usr/bin/env python3
"""Extract initialized C arrays into a generated R6RS library.

    c2scm.py OUT.sls "(doom lib-name)" SRC.c:array[:kind] ...

kind is "fx" (fxvector, the default) or "u8" (bytevector). Multi-dimensional
arrays are flattened row-major. Each array becomes an exported definition with
the C name, e.g. finesine. Only numeric initializers are supported.
"""
import re
import sys


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", " ", src, flags=re.S)
    return re.sub(r"//[^\n]*", " ", src)


def extract(src, name):
    m = re.search(r"\b%s\s*(\[[^\]]*\]\s*)+=\s*\{" % re.escape(name), src)
    if not m:
        sys.exit("array %s not found" % name)
    depth, i = 1, m.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    body = src[m.end():i - 1].replace("{", " ").replace("}", " ")
    return [int(tok, 0) for tok in re.findall(r"-?(?:0[xX][0-9a-fA-F]+|\d+)", body)]


def main():
    out, libname, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
    defs, names = [], []
    for spec in specs:
        path, name, *kind = spec.split(":")
        kind = kind[0] if kind else "fx"
        vals = extract(strip_comments(open(path).read()), name)
        prefix = {"fx": "#vfx(", "u8": "#vu8("}[kind]
        lines = [" ".join(str(v) for v in vals[j:j + 12]) for j in range(0, len(vals), 12)]
        body = ("\n" + " " * 4).join(lines)
        defs.append(";; %s: %d entries from %s\n  (define %s\n    %s%s))"
                    % (name, len(vals), path.split("reference/")[-1], name, prefix, body))
        names.append(name)
    with open(out, "w") as f:
        f.write("#!chezscheme\n;;; GENERATED by tools/c2scm.py from the linuxdoom-1.10 source. Do not edit.\n")
        f.write("(library %s\n  (export %s)\n  (import (chezscheme))\n\n  %s)\n"
                % (libname, " ".join(names), "\n\n  ".join(defs)))


main()
